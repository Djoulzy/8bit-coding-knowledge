def glyph(character):
    return [int(row, 2) for row in FONT.get(character, FONT['?']).split('/')]


def text_cell(code, alternate=False):
    """7x8 host cell; ALTCHAR adds inverse lowercase at $60-$7F.

    MouseText and flashing are not modeled; the game emits neither. Normal
    lowercase ($E0-$FF) works in both character sets, just as on the IIe.
    """
    character=chr(code+0x40 if code<0x20 else code&0x7F)
    rows=glyph(character)+[0]
    inverse=code<0x40 or alternate and 0x60<=code<0x80
    return [bytes(255 if bool(1<=x<=5 and bits&(32>>x)) != inverse else 0
                  for x in range(7)) for bits in rows]
